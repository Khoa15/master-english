#!/usr/bin/env python3
"""Builds app/src/main/res/values*/strings.xml from the strings_*.py tables.

Run from anywhere:  python3 tools/i18n/build_strings.py

The tables are the single source of truth: edit them, never the generated XML. Every table maps a string key to
one text per language (see langs.py). The build fails when a language is missing, when the format arguments
(%1$s, %2$d ...) of a translation differ from the English text, or when a key is defined twice.
"""
import glob
import importlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from langs import LANGS, FOLDERS, NAMES  # noqa: E402

RES = os.path.normpath(os.path.join(HERE, "..", "..", "app", "src", "main", "res"))
ARGS = re.compile(r"%\d\$[sd]")


def load():
    merged = {}
    for path in sorted([p for p in glob.glob(os.path.join(HERE, "strings_*.py")) if not p.endswith("strings_plurals.py")]):
        module = importlib.import_module(os.path.basename(path)[:-3])
        for key, texts in module.STRINGS.items():
            if key in merged:
                sys.exit("duplicate key: " + key)
            merged[key] = texts
    return merged


def validate(strings):
    errors = []
    for key, texts in strings.items():
        missing = [l for l in LANGS if not texts.get(l)]
        if missing:
            errors.append(f"{key}: missing {missing}")
            continue
        want = sorted(ARGS.findall(texts["en"]))
        for lang in LANGS:
            if sorted(ARGS.findall(texts[lang])) != want:
                errors.append(f"{key} [{lang}]: format arguments differ from English {want}: {texts[lang]}")
            if "%" in re.sub(ARGS, "", texts[lang]).replace("%%", ""):
                errors.append(f"{key} [{lang}]: stray % sign")
    if errors:
        sys.exit("\n".join(errors))


def escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text.startswith(("@", "?")):
        text = "\\" + text
    return text


def load_plurals():
    from strings_plurals import PLURALS
    for key, per_lang in PLURALS.items():
        for lang in LANGS:
            forms = per_lang.get(lang)
            if not forms or "other" not in forms:
                sys.exit(f"plural {key} [{lang}]: needs at least 'other'")
    return PLURALS


def write(strings, plurals):
    for lang in LANGS:
        folder = os.path.join(RES, FOLDERS[lang])
        os.makedirs(folder, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- GENERATED by tools/i18n/build_strings.py from tools/i18n/strings_*.py. Do not edit. -->",
                 "<resources>"]
        for key, texts in strings.items():
            lines.append(f'    <string name="{key}">{escape(texts[lang])}</string>')
        for key, per_lang in plurals.items():
            lines.append(f'    <plurals name="{key}">')
            for quantity, text in per_lang[lang].items():
                lines.append(f'        <item quantity="{quantity}">{escape(text)}</item>')
            lines.append("    </plurals>")
        lines.append("</resources>")
        with open(os.path.join(folder, "strings.xml"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")


def write_language_list():
    """The language list itself, derived from langs.py: the per-app locale config and the arrays the app reads."""
    config = ['<?xml version="1.0" encoding="utf-8"?>',
              "<!-- GENERATED by tools/i18n/build_strings.py from tools/i18n/langs.py. Do not edit. -->",
              '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">']
    config += [f'    <locale android:name="{code}" />' for code in LANGS]
    config.append("</locale-config>")
    with open(os.path.join(RES, "xml", "locales_config.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(config) + "\n")
    arrays = ['<?xml version="1.0" encoding="utf-8"?>',
              "<!-- GENERATED by tools/i18n/build_strings.py from tools/i18n/langs.py. Do not edit. -->",
              "<resources>", '    <string-array name="language_codes" translatable="false">']
    arrays += [f"        <item>{code}</item>" for code in LANGS]
    arrays += ["    </string-array>", '    <string-array name="language_names" translatable="false">']
    arrays += [f"        <item>{escape(NAMES[code])}</item>" for code in LANGS]
    arrays += ["    </string-array>", "</resources>"]
    with open(os.path.join(RES, "values", "languages.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(arrays) + "\n")


if __name__ == "__main__":
    table = load()
    validate(table)
    plural_table = load_plurals()
    write(table, plural_table)
    write_language_list()
    print(f"{len(table)} strings + {len(plural_table)} plurals x {len(LANGS)} languages written to {RES}")
